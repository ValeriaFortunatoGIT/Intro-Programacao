package Unidade5;

public class ForComFor {
    public static void main(String[] args) {
        for (int linha = 0; linha < 3; linha++) {
            for (int coluna = 0; coluna < 3; coluna++) {
                System.out.print("lin " + linha + " col" + coluna);
            }
            System.out.println("");
        }
    }
}
