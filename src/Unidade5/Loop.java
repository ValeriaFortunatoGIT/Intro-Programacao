package Unidade5;

import java.util.Scanner;

public class Loop {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        
        //Se usa o for quando você sabe quantas vezes vai ser usado, quando tem um limite, um início e um fim
        //Inicialização - onde começa / Condição de parada - até onde vai / Incremento - repetção
        //inicialização / condição de parada / incremento
        for(int i=0;i<11;i++){
            System.out.println(i);
        }
    }

}

